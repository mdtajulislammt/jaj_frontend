const productsSlice = createSlice({
  name: "products",
  initialState,
  reducers: {
    addProduct: {
      reducer(state, action) {
        state.items.push(action.payload);
      },
      prepare(product) {
        return { payload: { id: `p-${nanoid(6)}`, serials: [], ...product } };
      },
    },
    updateProduct(state, action) {
      const idx = state.items.findIndex((p) => p.id === action.payload.id);
      if (idx !== -1) state.items[idx] = { ...state.items[idx], ...action.payload };
    },
    removeProduct(state, action) {
      state.items = state.items.filter((p) => p.id !== action.payload);
    },
    addSerials(state, action) {
      const { productId, serials } = action.payload; // serials: [{imei, branch}]
      const product = state.items.find((p) => p.id === productId);
      if (!product) return;
      serials.forEach((s) => {
        product.serials.push({ imei: s.imei, status: "in_stock", branch: s.branch });
      });
    },
    setSerialStatus(state, action) {
      const { productId, imei, status } = action.payload;
      const product = state.items.find((p) => p.id === productId);
      if (!product) return;
      const serial = product.serials.find((s) => s.imei === imei);
      if (serial) serial.status = status;
    },
    resetToDemo(state) {
      state.items = JSON.parse(JSON.stringify(initialState.items));
      state.categories = JSON.parse(JSON.stringify(initialState.categories));
      state.brands = JSON.parse(JSON.stringify(initialState.brands));
    },
  },
});

export const {
  addProduct,
  updateProduct,
  removeProduct,
  addSerials,
  setSerialStatus,
  resetToDemo,
} = productsSlice.actions;
export default productsSlice.reducer;
